"""Deterministic TypeScript schema types from FastAPI OpenAPI, without a running server."""

import argparse
import json
from pathlib import Path

from benchwarden.main import app


def ts(schema):
    if "$ref" in schema:
        return f"API[{json.dumps(schema['$ref'].split('/')[-1])}]"
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(value) for value in schema["enum"])
    for key, operator in [("anyOf", " | "), ("oneOf", " | "), ("allOf", " & ")]:
        if key in schema:
            return "(" + operator.join(ts(item) for item in schema[key]) + ")"
    kind = schema.get("type")
    if kind == "array":
        return f"Array<{ts(schema.get('items', {}))}>"
    if kind == "object":
        properties = schema.get("properties")
        if properties is None:
            extra = schema.get("additionalProperties", {})
            return f"Record<string, {ts(extra) if isinstance(extra, dict) else 'unknown'}>"
        required = schema.get("required", [])
        if not properties:
            return "Record<string, never>"
        return (
            "{ "
            + "; ".join(
                f"{json.dumps(key)}{'' if key in required else '?'}: {ts(value)}"
                for key, value in sorted(properties.items())
            )
            + " }"
        )
    return {
        "string": "string",
        "integer": "number",
        "number": "number",
        "boolean": "boolean",
        "null": "null",
    }.get(kind, "unknown")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    content = (
        "// Generated by backend/scripts/generate_api_types.py. Do not edit.\nexport type API = {\n"
    )
    for name, schema in sorted(app.openapi()["components"]["schemas"].items()):
        content += f"  {json.dumps(name)}: {ts(schema)}\n"
    content += "}\n"
    target = Path(__file__).resolve().parents[2] / "frontend/src/api-types.ts"
    if args.check:
        if target.read_text(encoding="utf-8") != content:
            raise SystemExit("API types are stale; run python scripts/generate_api_types.py")
    else:
        target.write_text(content, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
